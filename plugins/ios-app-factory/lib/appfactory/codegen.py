"""Deterministic Swift code generation from artifacts.

* ``App/Sources/Design/DesignTokens.swift`` from design.json
* ``App/Sources/Store/ProductCatalog.swift`` from mvp.json
* ``App/Resources/Products.storekit`` (local StoreKit testing config) from mvp.json

Gates regenerate in memory and compare, so hand edits or forgotten
regeneration after a spec change are detected mechanically.
"""
from __future__ import annotations

import json
import uuid
from typing import Dict

from .color import hex_to_rgb
from .jsonio import read_json, write_text_atomic
from .project import Project

HEADER = "// GENERATED by ios-app-factory (`app-factory codegen`). Do not edit by hand.\n// Source: {src}\n\n"

DESIGN_TOKENS = "App/Sources/Design/DesignTokens.swift"
PRODUCT_CATALOG = "App/Sources/Store/ProductCatalog.swift"
STOREKIT_CONFIG = "App/Resources/Products.storekit"


def _swift_color(hex_value: str) -> str:
    r, g, b = hex_to_rgb(hex_value)
    return f"RGB({r / 255:.4f}, {g / 255:.4f}, {b / 255:.4f})"


def _camel(name: str) -> str:
    parts = name.split("_")
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


def design_tokens_swift(design: dict) -> str:
    light, dark = design["color"]["light"], design["color"]["dark"]
    keys = [k for k in ["background", "surface", "text_primary", "text_secondary", "accent", "accent_text", "separator"] if k in light and k in dark]
    lines = [HEADER.format(src="factory/artifacts/design/design.json"), "import SwiftUI\n", "import UIKit\n\n"]
    lines.append("/// Design concept: " + design["concept"]["name"].replace("\n", " ") + "\n")
    lines.append("enum DesignTokens {\n")
    lines.append("    struct RGB { let r: Double; let g: Double; let b: Double\n")
    lines.append("        init(_ r: Double, _ g: Double, _ b: Double) { self.r = r; self.g = g; self.b = b }\n")
    lines.append("        var uiColor: UIColor { UIColor(red: r, green: g, blue: b, alpha: 1) }\n    }\n\n")
    lines.append("    private static func dynamic(_ light: RGB, _ dark: RGB) -> Color {\n")
    lines.append("        Color(uiColor: UIColor { $0.userInterfaceStyle == .dark ? dark.uiColor : light.uiColor })\n    }\n\n")
    lines.append("    enum Palette {\n")
    for k in keys:
        lines.append(f"        static let {_camel(k)} = dynamic({_swift_color(light[k])}, {_swift_color(dark[k])})\n")
    lines.append("    }\n\n")
    typo = design["typography"]
    lines.append("    enum Typography {\n")
    lines.append(f"        static let design: Font.Design = .{typo['design']}\n")
    lines.append(f"        static let displayDesign: Font.Design = .{typo.get('display_design', typo['design'])}\n")
    for role, style in typo["text_styles"].items():
        d = "displayDesign" if role == "title" else "design"
        lines.append(f"        static let {role} = Font.system(.{style}, design: {d})\n")
    lines.append("    }\n\n")
    lines.append("    enum Metrics {\n")
    lines.append(f"        static let cornerRadius: CGFloat = {float(design['shape']['corner_radius'])}\n")
    lines.append(f"        static let spacing: CGFloat = {float(design['spacing']['unit'])}\n")
    lines.append(f"        static let cardStyle = \"{design['shape']['card_style']}\"\n")
    lines.append("    }\n}\n")
    return "".join(lines)


def product_catalog_swift(mvp: dict) -> str:
    products = mvp["monetization"]["products"]
    lines = [HEADER.format(src="factory/artifacts/mvp/mvp.json"), "import Foundation\n\n"]
    lines.append("/// In-app products defined by the MVP spec.\n")
    lines.append("enum ProductCatalog {\n")
    for p in products:
        ident = _camel(p["product_id"].split(".")[-1].replace("-", "_"))
        lines.append(f"    static let {ident} = \"{p['product_id']}\"\n")
    ids = ", ".join(f"\"{p['product_id']}\"" for p in products)
    lines.append(f"    static let all: [String] = [{ids}]\n")
    nc = ", ".join(f"\"{p['product_id']}\"" for p in products if p["type"] == "NON_CONSUMABLE")
    lines.append(f"    /// Non-consumables whose ownership unlocks Pro features.\n    static let proUnlocking: Set<String> = [{nc}]\n")
    feats = sorted({f for p in products for f in p["unlocks"]})
    lines.append(f"    /// MVP feature ids gated behind Pro.\n    static let proFeatureIDs: Set<String> = [{', '.join(chr(34) + f + chr(34) for f in feats)}]\n")
    prices = ", ".join(f'"{p["product_id"]}": Decimal(string: "{p["price_usd"]:.2f}") ?? 0' for p in products)
    lines.append(f"    /// Reference prices (USD) from mvp.json, used only by the UI-test mock store.\n")
    lines.append(f"    static let referencePriceUSD: [String: Decimal] = [{prices or ':'}]\n")
    lines.append("}\n")
    return "".join(lines)


DEFAULT_TERMS = "https://www.apple.com/legal/internet-services/itunes/dev/stdeula/"
PLACEHOLDER_HOST = "example.invalid"


def app_links(config: dict) -> dict:
    links = (config.get("app") or {}).get("links") or {}
    return {
        "support": links.get("support") or f"https://{PLACEHOLDER_HOST}/support",
        "privacyPolicy": links.get("privacy_policy") or f"https://{PLACEHOLDER_HOST}/privacy",
        "termsOfUse": links.get("terms") or DEFAULT_TERMS,
    }


def app_links_swift(config: dict) -> str:
    links = app_links(config)
    lines = [HEADER.format(src="factory/config.json app.links"), "import Foundation\n\n", "enum AppLinks {\n"]
    for name, url in links.items():
        lines.append(f'    static let {name} = URL(string: "{url}")!\n')
    lines.append("}\n")
    return "".join(lines)


APP_LINKS = "App/Sources/App/AppLinks.swift"


def _stable_uuid(seed: str) -> str:
    return str(uuid.uuid5(uuid.NAMESPACE_URL, "ios-app-factory:" + seed)).upper()


def storekit_config(mvp: dict, app_name: str) -> str:
    """Xcode StoreKit Configuration (.storekit, format version 3)."""
    type_map = {"NON_CONSUMABLE": "NonConsumable", "CONSUMABLE": "Consumable"}
    products = []
    for p in mvp["monetization"]["products"]:
        if p["type"] not in type_map:
            continue
        products.append({
            "displayPrice": f"{p['price_usd']:.2f}",
            "familyShareable": bool(p.get("family_sharable", False)),
            "internalID": _stable_uuid(p["product_id"])[:8],
            "localizations": [
                {"description": p["localizations"][loc]["description"], "displayName": p["localizations"][loc]["name"],
                 "locale": loc.replace("-", "_")}
                for loc in ("en-US", "ja")
            ],
            "productID": p["product_id"],
            "referenceName": p["reference_name"],
            "type": type_map[p["type"]],
        })
    doc = {
        "identifier": _stable_uuid(app_name + ":storekit")[:8],
        "nonRenewingSubscriptions": [],
        "products": products,
        "settings": {"_applicationInternalID": "", "_developerTeamID": "", "_failTransactionsEnabled": False,
                     "_locale": "en_US", "_storefront": "USA", "_storeKitErrors": []},
        "subscriptionGroups": [],
        "version": {"major": 3, "minor": 0},
    }
    return json.dumps(doc, ensure_ascii=False, indent=2, sort_keys=True) + "\n"


def expected_files(project: Project) -> Dict[str, str]:
    out = {}
    design = read_json(project.artifact("design", "design.json"))
    mvp = read_json(project.artifact("mvp", "mvp.json"))
    if design:
        out[DESIGN_TOKENS] = design_tokens_swift(design)
    if mvp:
        out[PRODUCT_CATALOG] = product_catalog_swift(mvp)
        out[STOREKIT_CONFIG] = storekit_config(mvp, project.config().get("app", {}).get("name", "App"))
    out[APP_LINKS] = app_links_swift(project.config())
    return out


def generate(project: Project) -> Dict[str, str]:
    written = {}
    for rel, content in expected_files(project).items():
        path = project.root / rel
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            write_text_atomic(path, content)
            written[rel] = "updated"
        else:
            written[rel] = "unchanged"
    return written
